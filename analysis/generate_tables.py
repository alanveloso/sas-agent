#!/usr/bin/env python3
"""Build compact Markdown/CSV tables from a campaign's raw artifacts.

Does not run the SAS agent or any benchmark — read-only over ``artifacts/raw``.
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from analysis.load_data import (  # noqa: E402
    latest_campaign,
    load_cert_matrix_summary,
    load_coldstart_summary,
    load_lifecycle_summary,
    load_mtls_overhead_summary,
    load_persistence_summary,
)

TABLES = REPO / "artifacts" / "tables"


def _write_csv(path: Path, rows: list[dict], fields: list[str] | None = None) -> None:
    if not rows:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    keys = fields or list(rows[0].keys())
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=keys, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def _md_table(headers: list[str], rows: list[list[str]]) -> list[str]:
    lines = [
        "| " + " | ".join(headers) + " |",
        "|" + "|".join("---" for _ in headers) + "|",
    ]
    for row in rows:
        lines.append("| " + " | ".join(row) + " |")
    return lines


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--campaign-id", default=None)
    args = p.parse_args()
    campaign = args.campaign_id or latest_campaign()
    if not campaign:
        print("no campaign under artifacts/raw/", file=sys.stderr)
        return 1

    out_dir = TABLES / campaign
    out_dir.mkdir(parents=True, exist_ok=True)
    md: list[str] = [
        f"# Tables — campaign `{campaign}`",
        "",
        "Generated by `analysis/generate_tables.py` (read-only).",
        "",
    ]

    life = load_lifecycle_summary(campaign)
    if life:
        _write_csv(out_dir / "lifecycle_summary.csv", life)
        focus = [r for r in life if r.get("profile_id") == "cbrs_winnforum"]
        md += ["## Lifecycle decomposition (cbrs_winnforum)", ""]
        headers = ["operation", "metric", "median", "iqr", "p95", "n"]
        body = [
            [r.get("operation", ""), r.get("metric", ""), r.get("median", ""),
             r.get("iqr", ""), r.get("p95", ""), r.get("n", "")]
            for r in focus
            if r.get("metric") in (
                "client_ms", "application_non_db_ms", "database_ms",
                "external_ms", "stage_handler_ms", "stage_database_ms",
                "stage_serialization_ms", "stage_other_ms", "contrib_pct",
            )
        ]
        md += _md_table(headers, body) + [""]

    mtls = load_mtls_overhead_summary(campaign)
    if mtls:
        _write_csv(out_dir / "mtls_overhead_summary.csv", mtls)
        md += ["## mTLS overhead", ""]
        headers = ["condition", "metric", "median", "p95", "n_blocks"]
        body = [
            [r.get("condition", ""), r.get("metric", ""), r.get("median", ""),
             r.get("p95", ""), r.get("n_blocks", "")]
            for r in mtls
            if r.get("metric") in ("latency_median_ms", "latency_p95_ms", "throughput_rps")
        ]
        md += _md_table(headers, body) + [""]

    cert = load_cert_matrix_summary(campaign)
    if cert:
        _write_csv(out_dir / "cert_matrix_summary.csv", cert)
        md += ["## Certificate matrix", ""]
        body = [[r.get("metric", ""), r.get("value", "")] for r in cert]
        md += _md_table(["metric", "value"], body) + [""]

    pers = load_persistence_summary(campaign)
    if pers:
        _write_csv(out_dir / "persistence_summary.csv", pers)
        md += ["## Persistence", ""]
        headers = ["mode", "devices", "metric", "median", "iqr", "n"]
        body = [
            [r.get("persist_mode", ""), r.get("devices", ""), r.get("metric", ""),
             r.get("median", ""), r.get("iqr", ""), r.get("n_repeats", "")]
            for r in pers
            if r.get("metric") in (
                "population_wall_sec", "database_ms_sum", "probe_grant_mean_ms",
            )
        ]
        md += _md_table(headers, body) + [""]

    cold = load_coldstart_summary(campaign)
    if cold:
        _write_csv(out_dir / "coldstart_summary.csv", cold)
        md += ["## Cold start", ""]
        headers = ["profile", "metric", "median", "p95", "n_ok"]
        body = [
            [r.get("profile_id", ""), r.get("metric", ""), r.get("median", ""),
             r.get("p95", ""), r.get("n_ok", "")]
            for r in cold
        ]
        md += _md_table(headers, body) + [""]

    md_path = out_dir / "tables.md"
    md_path.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"Wrote {md_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
